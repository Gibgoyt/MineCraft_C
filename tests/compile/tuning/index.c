static void tt_join(char *out, const char *directory, const char *name) {
    const int32_t length = snprintf(out, TT_PATH_BYTES, "%s/%s", directory, name);
    if (length < 0 || (uint32_t)length >= TT_PATH_BYTES) {
        printf("FAIL path too long: %s/%s\n", directory, name);
        _exit(1);
    }
}

/* Makes each missing directory of path. */
static void tt_make_directories(const char *path) {
    char partial[TT_PATH_BYTES];
    const uint64_t length = strlen(path);
    if (length >= sizeof(partial)) {
        printf("FAIL path too long: %s\n", path);
        _exit(1);
    }
    memcpy(partial, path, length + 1u);
    for (uint64_t i = 1u; i <= length; i++) {
        if (partial[i] == '/' || partial[i] == '\0') {
            const char kept = partial[i];
            partial[i] = '\0';
            if (mkdir(partial, 0755) != 0 && errno != EEXIST) {
                printf("FAIL cannot create %s: %s\n", partial, strerror(errno));
                _exit(1);
            }
            partial[i] = kept;
        }
    }
}

/* Writes root/<relative>/index.yaml, making its directories. */
static void tt_write_yaml(const char *root, const char *relative, const char *text, uint64_t length) {
    char directory[TT_PATH_BYTES];
    char path[TT_PATH_BYTES];
    tt_join(directory, root, relative);
    tt_make_directories(directory);
    tt_join(path, directory, "index.yaml");
    const int32_t descriptor = open(path, O_WRONLY | O_CREAT | O_TRUNC | O_CLOEXEC, 0644);
    if (descriptor < 0 || write(descriptor, text, length) != (int64_t)length) {
        printf("FAIL cannot write %s\n", path);
        _exit(1);
    }
    close(descriptor);
}

/* Reads a whole file and NUL-terminates it. Returns false if it cannot, or if it does not fit. */
static bool tt_read_file(const char *path, uint8_t *out, uint64_t *out_length) {
    const int32_t descriptor = open(path, O_RDONLY | O_CLOEXEC);
    if (descriptor < 0) {
        return false;
    }
    uint64_t total = 0u;
    bool ok = true;
    while (total + 1u < TT_FILE_BYTES) {
        const int64_t got = read(descriptor, out + total, TT_FILE_BYTES - 1u - total);
        if (got < 0) {
            ok = false;
        }
        if (got <= 0) {
            break;
        }
        total += (uint64_t)got;
    }
    close(descriptor);
    out[total] = 0u;
    *out_length = total;
    return ok && total + 1u < TT_FILE_BYTES;
}

static bool tt_exists(const char *path) {
    struct stat status;
    return stat(path, &status) == 0;
}

static int64_t tt_mtime(const char *path) {
    struct stat status;
    return stat(path, &status) == 0 ? (int64_t)status.st_mtim.tv_sec : -1;
}

static void tt_set_old(const char *path) {
    const struct timespec times[2] = {{.tv_sec = TT_OLD_SECONDS, .tv_nsec = 0},
                                      {.tv_sec = TT_OLD_SECONDS, .tv_nsec = 0}};
    if (utimensat(AT_FDCWD, path, times, 0) != 0) {
        printf("FAIL cannot set the time of %s: %s\n", path, strerror(errno));
        _exit(1);
    }
}

static const tt_paths_t *tt_paths(test_context_t *t) {
    if (t->arg_count != 4) {
        printf("usage: tool real_config generated_tuning_dir work_dir\n");
        _exit(2);
    }
    tt_paths_t *paths = test_alloc(t, sizeof(tt_paths_t));
    *paths = (tt_paths_t){
        .tool = t->borrowed_args[0],
        .real_config = t->borrowed_args[1],
        .generated = t->borrowed_args[2],
        .work_dir = t->borrowed_args[3],
    };
    tt_make_directories(paths->work_dir);
    return paths;
}

/* A fresh directory for one test, work/<name>, with nothing left from the last run. Its config/ and out/ go in it. */
static void tt_case(test_context_t *t, const tt_paths_t *paths, const char *name, char *out_root) {
    tt_join(out_root, paths->work_dir, name);
    char *const remove[] = {(char *)"rm", (char *)"-rf", out_root, nullptr};
    test_process_t process;
    test_process_run(t, remove, TT_TIMEOUT_MS, &process);
    CHECK(process.exit_code == 0);
    tt_make_directories(out_root);
}

/* Runs the tool on root/config into root/out, with root/stamp. */
static void tt_run(test_context_t *t, const tt_paths_t *paths, const char *root, test_process_t *out) {
    char config[TT_PATH_BYTES];
    char output[TT_PATH_BYTES];
    char stamp[TT_PATH_BYTES];
    tt_join(config, root, "config");
    tt_join(output, root, "out");
    tt_join(stamp, root, "stamp");
    char *const argv[] = {
        (char *)paths->tool, (char *)"--config", config, (char *)"--out", output, (char *)"--stamp", stamp, nullptr};
    test_process_run(t, argv, TT_TIMEOUT_MS, out);
}

/* out receives the fixture with its only occurrence of from replaced. Fails the run if from is not in it exactly once. */
static uint64_t tt_mutate(char *out, const char *from, const char *to) {
    const char *at = strstr(TT_FIXTURE, from);
    if (at == nullptr || strstr(at + 1, from) != nullptr) {
        printf("FAIL the fixture must hold '%s' exactly once\n", from);
        _exit(1);
    }
    const uint64_t prefix = (uint64_t)(at - TT_FIXTURE);
    const int32_t length = snprintf(out, TT_FILE_BYTES, "%.*s%s%s", (int32_t)prefix, TT_FIXTURE, to, at + strlen(from));
    return (uint64_t)length;
}

/* The fixture as render/shade, run. */
static void tt_run_fixture(test_context_t *t, const tt_paths_t *paths, const char *root, const char *text,
                           test_process_t *out) {
    char config[TT_PATH_BYTES];
    tt_join(config, root, "config");
    tt_write_yaml(config, "render/shade", text, strlen(text));
    tt_run(t, paths, root, out);
}

/* The text of one generated file under root/out, in tt_buffer_a. */
static const char *tt_output(const char *root, const char *relative) {
    char path[TT_PATH_BYTES];
    char out[TT_PATH_BYTES];
    tt_join(out, root, "out");
    tt_join(path, out, relative);
    uint64_t length = 0u;
    if (!tt_read_file(path, tt_buffer_a, &length)) {
        printf("  cannot read %s\n", path);
        tt_buffer_a[0] = 0u;
    }
    return (const char *)tt_buffer_a;
}

/* The MC_TUNE_HASH line of root/out/hash/index.h, into line. */
static void tt_hash_line(const char *root, char *line, uint64_t capacity) {
    const char *text = tt_output(root, "hash/index.h");
    const char *at = strstr(text, "#define MC_TUNE_HASH ");
    const char *end = at != nullptr ? strchr(at, '\n') : nullptr;
    const uint64_t length = end != nullptr ? (uint64_t)(end - at) : 0u;
    snprintf(line, capacity, "%.*s", (int32_t)(length < capacity ? length : capacity - 1u), at != nullptr ? at : "");
}

TEST(a_good_file_gives_the_defines_it_says) {
    const tt_paths_t *paths = tt_paths(t);
    char root[TT_PATH_BYTES];
    tt_case(t, paths, "good", root);
    test_process_t process;
    tt_run_fixture(t, paths, root, TT_FIXTURE, &process);
    if (process.exit_code != 0) {
        printf("  tool said: %s", process.output);
    }
    CHECK_EQ_I64(process.exit_code, 0);
    CHECK_STR_EQ(tt_output(root, "render/shade/index.h"), TT_EXPECTED_H);

    /* The .hu is the same but for its guard. */
    memcpy(tt_text, TT_EXPECTED_H, sizeof(TT_EXPECTED_H));
    char *guard = tt_text;
    while ((guard = strstr(guard, "_INDEX_H\n")) != nullptr) {
        memmove(guard + 9, guard + 8, strlen(guard + 8) + 1u);
        guard[8] = 'U';
        guard += 9;
    }
    CHECK_STR_EQ(tt_output(root, "render/shade/index.hu"), tt_text);

    const char *summary = tt_output(root, "hash/index.h");
    CHECK_CONTAINS(summary, "#define MC_TUNE_KEY_COUNT 4u\n");
    CHECK_CONTAINS(summary, "    \"render/shade count 16\\n\" \\\n"
                            "    \"render/shade offset -2\\n\" \\\n"
                            "    \"render/shade reach 3.0\\n\" \\\n"
                            "    \"render/shade switch true\\n\" \\\n"
                            "    \"\"\n");
    char stamp[TT_PATH_BYTES];
    tt_join(stamp, root, "stamp");
    CHECK(tt_exists(stamp));
}

TEST(a_decimal_comes_out_as_written) {
    const tt_paths_t *paths = tt_paths(t);
    char root[TT_PATH_BYTES];
    tt_case(t, paths, "decimals", root);
    static const char *const values[] = {"0.1", "1.25", "0.000004", "16.0", "0.0625", "-0.5", "100.0"};
    uint64_t length = 0u;
    for (uint32_t i = 0u; i < sizeof(values) / sizeof(values[0]); i++) {
        length +=
            (uint64_t)snprintf(tt_text + length, TT_FILE_BYTES - length,
                               "k%" PRIu32 ":\n  value: %s\n  type: f32\n  unit: ratio\n  min: -1.0\n  max: 100.0\n"
                               "  why: \"As written.\"\n",
                               i, values[i]);
    }
    test_process_t process;
    tt_run_fixture(t, paths, root, tt_text, &process);
    CHECK_EQ_I64(process.exit_code, 0);
    const char *header = tt_output(root, "render/shade/index.h");
    CHECK_CONTAINS(header, "#define MC_TUNE_RENDER_SHADE_K0 F32(0.1) /* ratio, -1.0..100.0 */\n");
    CHECK_CONTAINS(header, "#define MC_TUNE_RENDER_SHADE_K1 F32(1.25) /*");
    CHECK_CONTAINS(header, "#define MC_TUNE_RENDER_SHADE_K2 F32(0.000004) /*");
    CHECK_CONTAINS(header, "#define MC_TUNE_RENDER_SHADE_K3 F32(16.0) /*");
    CHECK_CONTAINS(header, "#define MC_TUNE_RENDER_SHADE_K4 F32(0.0625) /*");
    CHECK_CONTAINS(header, "#define MC_TUNE_RENDER_SHADE_K5 (F32(-0.5)) /*");
    CHECK_CONTAINS(header, "#define MC_TUNE_RENDER_SHADE_K6 F32(100.0) /*");
    /* What the literals were in code before they moved, to the bit: F32(0.1) is what POST_TAA_BLEND was, and 4e-6F the pad. */
    CHECK(F32(0.000004) == F32(4e-6));
}

TEST(each_mistake_is_refused_at_its_line) {
    const tt_paths_t *paths = tt_paths(t);
    for (uint32_t i = 0u; i < sizeof(TT_BAD_CASES) / sizeof(TT_BAD_CASES[0]); i++) {
        const tt_bad_case_t *bad = &TT_BAD_CASES[i];
        char root[TT_PATH_BYTES];
        char name[32];
        snprintf(name, sizeof(name), "bad_%02" PRIu32, i);
        tt_case(t, paths, name, root);
        tt_mutate(tt_text, bad->from, bad->to);
        test_process_t process;
        tt_run_fixture(t, paths, root, tt_text, &process);
        char where[128];
        snprintf(where, sizeof(where), "render/shade/index.yaml:%" PRIu32 ":%" PRIu32 ": %s", bad->line, bad->column,
                 bad->expected);
        if (process.exit_code != TUNING_EXIT_REFUSED || strstr(process.output, where) == nullptr) {
            printf("  case %" PRIu32 " (%s -> %s): wanted %s, got %" PRId32 ": %s", i, bad->from, bad->to, where,
                   process.exit_code, process.output);
        }
        CHECK_EQ_I64(process.exit_code, TUNING_EXIT_REFUSED);
        CHECK(strstr(process.output, where) != nullptr);
        CHECK(strstr(process.output, "nothing was written") != nullptr);
        char out[TT_PATH_BYTES];
        tt_join(out, root, "out");
        CHECK(!tt_exists(out));
    }
}

/* Every problem in a run is printed, not only the first, and across files. */
TEST(every_problem_is_printed) {
    const tt_paths_t *paths = tt_paths(t);
    char root[TT_PATH_BYTES];
    char config[TT_PATH_BYTES];
    tt_case(t, paths, "many", root);
    tt_join(config, root, "config");
    const uint64_t length = tt_mutate(tt_text, "  value: 16\n", "  value: 65\n");
    tt_write_yaml(config, "render/shade", tt_text, length);
    tt_mutate(tt_text, "  unit: count\n", "  unit: furlongs\n");
    tt_write_yaml(config, "render/lod", tt_text, strlen(tt_text));
    static const char root_file[] = "a:\n  value: 1\n  type: u32\n  unit: count\n  min: 0\n  max: 1\n  why: x\n";
    tt_write_yaml(root, "config", root_file, sizeof(root_file) - 1u);
    static const char upper_file[] = "a:\n  value: 1\n  type: u32\n  unit: count\n  min: 0\n  max: 1\n  why: x\n";
    tt_write_yaml(config, "Render", upper_file, sizeof(upper_file) - 1u);
    tt_write_yaml(config, "hash/x", upper_file, sizeof(upper_file) - 1u);
    test_process_t process;
    tt_run(t, paths, root, &process);
    CHECK_EQ_I64(process.exit_code, TUNING_EXIT_REFUSED);
    CHECK_CONTAINS(process.output, "render/lod/index.yaml:5:9: unknown unit 'furlongs'");
    CHECK_CONTAINS(process.output, "render/shade/index.yaml:3:10: 65 is outside 1..64");
    CHECK_CONTAINS(process.output, "config/index.yaml:1:1: an index.yaml goes in a directory below");
    CHECK_CONTAINS(process.output, "Render/index.yaml:1:1: each directory of the path is lower snake case");
    CHECK_CONTAINS(process.output, "hash/x/index.yaml:1:1: hash/ is where the hash of them all is written");
    CHECK_CONTAINS(process.output, "tuning: 5 problems; nothing was written");
}

